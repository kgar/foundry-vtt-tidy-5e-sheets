import type { FilterDescription } from 'src/foundry/dnd5e.types';
import type { ThemeSettingsV3 } from 'src/theme/theme-quadrone.types';

export interface GlobalCustomSectionSheetFilters {
  [sheetType: string]: string[];
}

export interface GlobalCustomSectionsetting {
  /** The section name. Localizable keys are also supported. */
  section: string;

  /** Determines whether the section should be visible even when there are no items  */
  showWhenEmpty: boolean;

  /**
   * Limits this section to the indicated sheet types' indicated tab IDs
   * when utilizing default custom sections.
   * If this object empty, then apply this section to all sheet types and all tabs.
   */
  showWhenEmptyFilters: GlobalCustomSectionSheetFilters;
}

export type SheetTabConfigEntry = {
  key: string;
  order: number;
  show: boolean;
  visibilityLevel: number;
};

export type SheetTabsConfiguration = {
  tabs: Record<string, SheetTabConfigEntry>;
};

export type SheetTabsConfigurationLegacyV1 = {
  selected: string[];
  visibilityLevels: Record<string, number | null>;
};

export type TabConfiguration = {
  [documentName: string]: {
    [documentType: string]: SheetTabsConfiguration;
  };
};

export type SheetHeaderControlConfiguration = {
  header: string[];
  menu: string[];
};

export type HeaderControlConfiguration = {
  [documentName: string]: {
    [documentType: string]: SheetHeaderControlConfiguration;
  };
};

/**
 * A world themes setting entry to be used in the Tidy world theme engine.
 */
export type WorldThemeSetting = {
  /** A unique identifier, usually generated by Tidy during settings management, to denote which world theme this is. */
  id: string;
  /** A display name for the world theme. */
  name: string;
  /** An optional filter for document name, e.g. "Actor" or "Item" */
  documentNames?: string[];
  /** An optional filter for document type, e.g. "weapon", "equipment", "character", "npc", "loot", etc. */
  types?: string[];
  /** The intended priority order of this theme setting. The UI reflects this sort order during settings management. */
  sort: number;
  /** The actual theme settings. */
  settings: Partial<ThemeSettingsV3>;
  /**
   * An optional filter to be evaluated when determining which theme should apply.
   * It is meant to be structured like the a dnd5e system FilterDescription or a FilterDescription array.
   */
  filter?: string;
  /**
   * Denotes whether this theme's filters were configured in basic or advanced mode.
   */
  filterMode: 'basic' | 'advanced';
};

/** All of the user-configured world themes. */
export type WorldThemesSetting = Record<string, WorldThemeSetting>;
